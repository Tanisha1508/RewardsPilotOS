"""One command that reproduces every measurable evaluation in this repo.

    python -m evaluation.run_all

Runs the quality suites (`evaluation.metrics.report`) and the performance and
reliability benchmark (`evaluation.benchmarks.performance`), writes their raw
results, and regenerates `reports/EVALUATION_REPORT.md` from those results
rather than from anything typed by hand. Nothing in the report is authored; if a
number appears there, this run produced it.

Exit status is the quality suites' own: zero when the deterministic suites are
green, non-zero otherwise, so CI can gate on it. The performance benchmark does
not gate — latency on whatever machine happens to run it is not a pass/fail
property, and a threshold here would either be meaningless or flaky.

What this deliberately does NOT run, and why it would be wrong to add casually:

* **Anything that calls the real model.** The Planner and Recommender run on a
  shared free-tier quota that the deployed app depends on. A judge-based
  faithfulness suite over a golden set would exhaust a day's quota and leave
  the live demo answering from the fallback provider. `evaluation/smoke/` exists
  for deliberate, small, live checks and is run by hand.
* **Load against the deployed service.** It is a 512 MB free instance with a
  measured 432 MB peak and a per-user daily question limit. Generating load
  would breach the limit, spend the same shared quota, and can plausibly take
  the instance down. Concurrency is measured locally instead, against the
  retrieval stage, where it costs nothing and answers the same question about
  our own code.
"""

import json
import sys
from pathlib import Path

from evaluation.benchmarks import performance
from evaluation.metrics import report as quality_report

REPORTS = Path(__file__).resolve().parent / "reports"
RAW = REPORTS / "raw_results.json"


def _bar(value: float, largest: float, width: int = 32) -> str:
    """A dependency-free bar. matplotlib is not a dependency of this project and
    BUILD_SPEC forbids adding one for a chart, so charts are drawn in text."""
    if largest <= 0:
        return ""
    return "█" * max(1, round((value / largest) * width))


def _latency_chart(latency: list[dict]) -> list[str]:
    stages = [s for s in latency if "p50_ms" in s]
    if not stages:
        return []
    largest = max(s["p50_ms"] for s in stages)
    lines = ["```", "Median latency by stage (ms, log-scale would flatten this — read the numbers)", ""]
    for stage in stages:
        lines.append(f"{stage['stage']:<34} {stage['p50_ms']:>8.2f}  {_bar(stage['p50_ms'], largest)}")
    lines.append("```")
    return lines


def main() -> int:
    # Performance first, and the order is load-bearing. The quality suites query
    # the same retriever, so running them first leaves the corpus warm and the
    # "cold first call" figure measures nothing — it read 15.91 ms that way,
    # against 477 ms genuinely cold.
    perf = performance.run()
    quality_markdown, quality_summary = quality_report.build_report()

    REPORTS.mkdir(parents=True, exist_ok=True)
    RAW.write_text(json.dumps({"quality": quality_summary, "performance": perf}, indent=2) + "\n")

    lines = [
        "# Evaluation report — generated",
        "",
        "Generated by `python -m evaluation.run_all`. Every number below is the",
        "output of that run. Nothing here is typed by hand, and nothing is",
        "estimated: a metric that could not be measured is absent rather than",
        "guessed at.",
        "",
        quality_markdown,
        "",
        "## Latency (deterministic stages, local machine, model time excluded)",
        "",
        f"Repeats per stage: {perf['repeats']}. {perf['note']}",
        "",
        "| Stage | Workload | p50 (ms) | p95 (ms) | mean (ms) | max (ms) |",
        "|---|---|---|---|---|---|",
    ]
    for stage in perf["latency"]:
        if "p50_ms" not in stage:
            continue
        lines.append(
            f"| `{stage['stage']}` | {stage['workload']} | {stage['p50_ms']} | "
            f"{stage['p95_ms']} | {stage['mean_ms']} | {stage['max_ms']} |"
        )

    cold = next((s.get("cold_first_call_ms") for s in perf["latency"] if s.get("cold_first_call_ms")), None)
    if cold:
        lines += [
            "",
            f"First retrieval call after process start: **{cold} ms**, reported "
            "separately because the corpus loads lazily and the first call is a "
            "different event from the rest (KNOWN_LIMITATIONS 28).",
        ]

    orchestration = next(
        (s for s in perf["latency"] if s["stage"].startswith("langgraph")), None
    )
    if orchestration:
        lines += [
            "",
            f"LangGraph orchestration over {orchestration['workload']}: "
            f"**{orchestration['per_query_mean_ms']} ms per query**, excluding "
            f"{orchestration['excludes']}. This is the cost of our own code — "
            "state handling, tool dispatch, contract validation — and is not "
            "what a user waits for.",
        ]

    lines += ["", *_latency_chart(perf["latency"])]

    lines += [
        "",
        "## Reliability (golden-set completion, deterministic paths)",
        "",
        "| Path | Cases | Passed | Success rate |",
        "|---|---|---|---|",
    ]
    for name, block in perf["reliability"].items():
        lines.append(
            f"| {name.replace('_', ' ')} | {block['total']} | {block['passed']} | "
            f"{block['success_rate']:.4f} |"
        )
    lines += [
        "",
        "A tool that refuses to compute on unverified data counts as a success:",
        "refusing is the specified behaviour, and scoring it as a failure would",
        "reward a system that guesses.",
        "",
    ]

    (REPORTS / "EVALUATION_REPORT.md").write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nWritten: {REPORTS / 'EVALUATION_REPORT.md'}")
    print(f"Written: {RAW}")

    green = (
        quality_summary["rules_exact_match"] == 1.0
        and quality_summary["graph_exact_match"] == 1.0
        and quality_summary["e2e_pass_rate"] == 1.0
    )
    return 0 if green else 1


if __name__ == "__main__":
    sys.exit(main())
